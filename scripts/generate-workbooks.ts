import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fixtures, SAMPLE_CAMPAIGNS_CSV } from "./workbook-fixtures";

const out = "data/templates";
const all = await fixtures();
const lines = ["# Workbook fixtures (generated by `npm run template`)", "", "| File | Mode | Expected | What it contains |", "|---|---|---|---|"];
for (const [name, f] of Object.entries(all)) {
  const p = join(out, name);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, f.buf);
  lines.push(`| \`${name}\` | ${f.mode} | ${f.valid ? "accepted" : "rejected"} | ${f.description} |`);
}
mkdirSync(join(out, "valid"), { recursive: true });
writeFileSync(join(out, "valid/campaigns-read-only.csv"), SAMPLE_CAMPAIGNS_CSV);
lines.push("| `valid/campaigns-read-only.csv` | merge (CSV, entity=campaigns) | accepted | Sets cmp-syn-4081 permissions to READ only → the next rush is BLOCKED_MISSING_PERMISSION. |");
writeFileSync(join(out, "README.md"), lines.join("\n") + "\n");
console.log(`wrote ${Object.keys(all).length + 1} files to ${out}`);
